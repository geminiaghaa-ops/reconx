"""WAF / CDN fingerprinting from HTTP responses.

Knowing a host sits behind Cloudflare/Akamai/Incapsula/etc. explains a lot: why
a "live" host returns 403/503 to tools, why direct IP access differs, and which
origin-discovery techniques are worth trying. Detection is header/cookie/CNAME
based, so it needs no external service.
"""
from __future__ import annotations

import re

# (label, kind, header-or-cookie regex over the serialized headers+cookies)
_SIGS: list[tuple[str, str, re.Pattern]] = [
    ("Cloudflare", "both", re.compile(r"(?i)\bcf-ray\b|server:\s*cloudflare|__cf_bm|__cflb|cf-cache-status")),
    ("Akamai", "cdn", re.compile(r"(?i)akamaighost|x-akamai|akamai-|x-akamai-transformed")),
    ("Fastly", "cdn", re.compile(r"(?i)x-served-by:\s*cache-|x-fastly|fastly-|via:[^\n]*varnish")),
    ("CloudFront", "cdn", re.compile(r"(?i)x-amz-cf-id|via:[^\n]*cloudfront|server:\s*cloudfront")),
    ("Azure Front Door", "cdn", re.compile(r"(?i)x-azure-ref|x-fd-|x-cache:[^\n]*azure")),
    ("Google", "cdn", re.compile(r"(?i)via:[^\n]*google|server:\s*gws|x-goog-")),
    ("Sucuri", "both", re.compile(r"(?i)x-sucuri-id|x-sucuri-cache|server:\s*sucuri")),
    ("Imperva/Incapsula", "waf", re.compile(r"(?i)x-iinfo|incap_ses|visid_incap|x-cdn:\s*incapsula")),
    ("F5 BIG-IP", "waf", re.compile(r"(?i)\bbigipserver|\bts[0-9a-f]{8}=|x-waf-")),
    ("AWS WAF", "waf", re.compile(r"(?i)x-amzn-waf|awselb/")),
    ("ModSecurity", "waf", re.compile(r"(?i)mod_security|modsecurity|this error was generated by mod_security")),
    ("Barracuda", "waf", re.compile(r"(?i)barra_counter_session|barracuda")),
    ("Wordfence", "waf", re.compile(r"(?i)wordfence|this response was generated by wordfence")),
    ("DDoS-Guard", "both", re.compile(r"(?i)ddos-guard|__ddg")),
    ("StackPath", "cdn", re.compile(r"(?i)x-sp-|stackpath")),
]

_CNAME_SIGS = [
    ("Cloudflare", "cdn", (".cloudflare.net",)),
    ("Akamai", "cdn", (".akamai.net", ".akamaiedge.net", ".edgekey.net", ".edgesuite.net")),
    ("Fastly", "cdn", (".fastly.net",)),
    ("CloudFront", "cdn", (".cloudfront.net",)),
    ("Azure Front Door", "cdn", (".azureedge.net", ".azurefd.net")),
    ("Imperva/Incapsula", "waf", (".incapdns.net",)),
]


def detect(headers: dict | str, cname: str = "", body_snippet: str = "") -> tuple[str, str]:
    """Return (cdn, waf) labels (either may be empty)."""
    if isinstance(headers, dict):
        blob = "\n".join(f"{k}: {v}" for k, v in headers.items())
    else:
        blob = str(headers)
    blob = blob + "\n" + (body_snippet or "")[:2000]

    cdn, waf = "", ""
    for label, kind, rx in _SIGS:
        if rx.search(blob):
            if kind in ("cdn", "both") and not cdn:
                cdn = label
            if kind in ("waf", "both") and not waf:
                waf = label
    cl = (cname or "").lower()
    if cl:
        for label, kind, suffixes in _CNAME_SIGS:
            if any(cl.endswith(s) or s.strip(".") in cl for s in suffixes):
                if kind == "cdn" and not cdn:
                    cdn = label
                if kind == "waf" and not waf:
                    waf = label
    return cdn, waf
